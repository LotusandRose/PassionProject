alpha = 2.0
T = 5.0  ##This T is different, but still go ham
epsilon = 0.001

s_initial = -15.0
s_final = 15.0

initial_conditions = [epsilon, 0.0]

def scalar_field(s, state):

    y, z = state

    dyds = z

    dzds = y * (
        1 - y**2
        - alpha**2 * np.tanh(s / T)**2
    )

    return [dyds, dzds]

s_values = np.linspace(s_initial, s_final, 2000)

solution = solve_ivp(
    scalar_field,
    (s_initial, s_final),
    initial_conditions,
    t_eval=s_values,
    method="DOP853",
    rtol=1e-9,
    atol=1e-11
)

if not solution.success:
    raise RuntimeError(solution.message)

s = solution.t
y = solution.y[0]
z = solution.y[1]

curvature = -1 + alpha**2 * np.tanh(s / T)**2

inside = curvature < 0

y_equilibrium = np.full_like(s, np.nan)
y_equilibrium[inside] = np.sqrt(-curvature[inside])

plt.figure(figsize=(10, 5))

plt.plot(s, y, label="Numerical field y(s)")
plt.plot(s[inside], y_equilibrium[inside],
         "--", label="Positive instantaneous minimum")
